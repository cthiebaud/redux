#!/usr/bin/env python3
"""Generate lyric-subtitle cues for the bateau_partiel_solo_guitar_0 video,
from bateau_ivre.yaml (the poem's words) and video_timeline.yaml (the real,
by-ear chord-cue timestamps for this take).

The target rhythm is one line every real bar (~3.43s at 70bpm, 4/4),
starting at START -- but a pure arithmetic grid (START + i*interval)
drifts out of sync with the actual chord changes: the real tempo isn't
perfectly constant (confirmed by measuring the drift against
video_timeline.yaml's cue timestamps -- up to ~0.4s off by the 2nd Vamp,
which reads as a real desync). So each tick instead SNAPS to the nearest
real cue start within half a bar, correcting drift every step instead of
accumulating it.

Only where no real cue falls nearby -- the 12-bar D7-pedal drone, the
ad-lib tail, and everything past the end of the take's chord data (i.e.
the printed-only continuation) -- is there nothing to snap to, and the
step is a flat one bar instead, computed from the piece's actual 70bpm
rather than guessed, since there's no measured data there to correct
against.

Run after editing bateau_ivre.yaml or video_timeline.yaml:
    python3 generate_subtitles.py
"""

import pathlib
import yaml

HERE = pathlib.Path(__file__).parent
BATEAU_DIR = HERE.parent
IVRE_YAML = BATEAU_DIR / "bateau_ivre.yaml"
TIMELINE_YAML = HERE / "video_timeline.yaml"
BUILD_DIR = HERE / "build"
DIST_DIR = HERE / "dist"
CUES_OUT = BUILD_DIR / "subtitles.yaml"
SRT_OUT = DIST_DIR / "bateau_video_draft.srt"

START = 35.75
BPM = 70
BAR = 4 * 60 / BPM  # one 4/4 bar at the piece's tempo: 3.42857...s -- the
# target cadence throughout: one real cue (D7, or the G7/D+C7/D half-bar
# pair, etc.) per bar, matching bateau.3.ly's own vampChordNames/
# sequenceChordNames/climaxChordNames. Confirmed against
# video_timeline.yaml (e.g. 39.19 - 35.75 = 3.44, a rounding hair off
# this exact value).


def load_lines():
    sections = yaml.safe_load(IVRE_YAML.read_text(encoding="utf-8"))
    by_number = {}
    for entry in sections:
        for strophe in entry["strophes"]:
            by_number[strophe["strophe"]] = strophe
    lines = []
    for n in sorted(by_number):
        lines.extend(by_number[n]["vers"])
    return lines


def load_timeline():
    data = yaml.safe_load(TIMELINE_YAML.read_text(encoding="utf-8"))
    real_starts = sorted({cue["start"] for cue in data["cues"]})
    return real_starts, data["duration"]


def snapped_ticks(start, interval, real_starts, end_limit):
    """Tick times starting at `start`, ~interval apart, snapped onto the
    nearest real cue start within half an interval when one exists (so
    drift is corrected every step, not accumulated) -- a flat step
    otherwise."""
    ticks = [start]
    t = start
    while True:
        target = t + interval
        candidates = [r for r in real_starts if r > t and abs(r - target) <= interval / 2]
        nxt = min(candidates, key=lambda r: abs(r - target)) if candidates else target
        if nxt > end_limit:
            break
        ticks.append(nxt)
        t = nxt
    return ticks


def build_subtitle_cues(lines, real_starts, duration):
    ticks = snapped_ticks(START, BAR, real_starts, duration)
    # Stop at the end of a complete quatrain (4 lines) rather than
    # wherever the audio happens to run out mid-stanza.
    n = min(len(lines), len(ticks))
    n -= n % 4
    out = []
    for i in range(n):
        start = ticks[i]
        end = ticks[i + 1] if i + 1 < len(ticks) else duration
        out.append({"start": start, "end": end, "text": lines[i]})
    return out


def srt_timestamp(t):
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = int(t % 60)
    ms = round((t - int(t)) * 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def write_srt(subtitle_cues, path):
    lines = []
    for i, cue in enumerate(subtitle_cues, start=1):
        lines.append(str(i))
        lines.append(f"{srt_timestamp(cue['start'])} --> {srt_timestamp(cue['end'])}")
        lines.append(cue["text"])
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    lines = load_lines()
    real_starts, duration = load_timeline()
    subtitle_cues = build_subtitle_cues(lines, real_starts, duration)

    BUILD_DIR.mkdir(exist_ok=True)
    DIST_DIR.mkdir(exist_ok=True)

    header = "# Generated by generate_subtitles.py -- do not edit by hand.\n\n"
    CUES_OUT.write_text(header + yaml.safe_dump(subtitle_cues, allow_unicode=True, sort_keys=False), encoding="utf-8")
    print(f"wrote {CUES_OUT} ({len(subtitle_cues)} cues)")

    write_srt(subtitle_cues, SRT_OUT)
    print(f"wrote {SRT_OUT}")


if __name__ == "__main__":
    main()
