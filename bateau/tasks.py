"""Invoke tasks for the bateau build pipeline.

Install once:
    pip install invoke pyyaml

Usage (run from anywhere -- all paths below are absolute):
    invoke            # full pipeline: lyrics, offsets, web svg, pdf/midi
    invoke --list     # list all tasks
    invoke clean build  # force a full rebuild

Pipeline:
    bateau_ivre.yaml ----------> lyrics  -> build/bateau_lyrics.ily
                                          -> build/bateau_poem_continuation.ily
    fret_diagram_chords.yaml --> offsets -> build/fret_diagram_offsets.scm

    bateau.3.ly + the above -----> websvg -> dist/bateau.3.web.svg
                                -> score  -> dist/bateau.3.pdf / .midi / -1.midi
"""

from pathlib import Path

from invoke import task

HERE = Path(__file__).resolve().parent
SCRIPTS = HERE / "scripts"
BUILD = HERE / "build"
DIST = HERE / "dist"
SCORE_LY = HERE / "bateau.3.ly"


def stale(output: Path, *sources: Path) -> bool:
    """True if `output` is missing or older than any of `sources`."""
    if not output.exists():
        return True
    out_mtime = output.stat().st_mtime
    return any(s.stat().st_mtime > out_mtime for s in sources)


@task
def lyrics(c, force=False):
    """build/bateau_lyrics.ily + build/bateau_poem_continuation.ily, from bateau_ivre.yaml."""
    out = BUILD / "bateau_lyrics.ily"
    src = HERE / "bateau_ivre.yaml"
    if force or stale(out, src):
        c.run(f"python3 {SCRIPTS / 'generate_lyrics.py'}")
    else:
        print(f"up to date: {out}")


@task
def offsets(c, force=False):
    """build/fret_diagram_offsets.scm, from fret_diagram_chords.yaml."""
    out = BUILD / "fret_diagram_offsets.scm"
    src = HERE / "fret_diagram_chords.yaml"
    if force or stale(out, src):
        c.run(f"python3 {SCRIPTS / 'measure_chord_widths.py'}")
    else:
        print(f"up to date: {out}")


def _score_sources():
    return [
        SCORE_LY,
        BUILD / "bateau_lyrics.ily",
        BUILD / "bateau_poem_continuation.ily",
        BUILD / "fret_diagram_offsets.scm",
    ]


@task(pre=[lyrics, offsets])
def websvg(c, force=False):
    """dist/bateau.3.web.svg -- the SVG bateau.3.html fetches at load time."""
    out = DIST / "bateau.3.web.svg"
    if force or stale(out, *_score_sources()):
        c.run(str(SCRIPTS / "build-web-svg.sh"))
    else:
        print(f"up to date: {out}")


@task(pre=[lyrics, offsets])
def score(c, force=False):
    """dist/bateau.3.pdf + .midi + -1.midi, compiled from bateau.3.ly."""
    out = DIST / "bateau.3.pdf"
    if force or stale(out, *_score_sources()):
        c.run(f"lilypond -o {DIST / 'bateau.3'} {SCORE_LY}")
    else:
        print(f"up to date: {out}")


@task(pre=[websvg, score], default=True)
def build(c):
    """Full pipeline: lyrics, offsets, web svg, pdf/midi."""


@task
def clean(c):
    """Remove build/ and dist/ -- everything there is regenerated by `invoke build`."""
    c.run(f"rm -rf {BUILD} {DIST}")
